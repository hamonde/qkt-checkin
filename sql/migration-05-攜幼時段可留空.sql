-- =========================================================
-- migration-05：攜幼／特殊入場時段改為可留空
-- 到 Supabase 後台 → SQL Editor → 開一個「新的空白分頁」→ 貼上整份 → Run
--
-- 這份跟前幾份不一樣，它會「填寫」現有場次的兩個時間欄位。
--
-- 為什麼要填？
--   在此之前，這兩欄留空時，程式會自動套用預設的 12:50 / 13:15。
--   從這次改版開始，「留空」有了新的意思 ——
--   代表這場沒有攜幼／特殊入場的分流，報到時間不做顏色判斷。
--   如果不先把現有場次填上實際使用的時間，
--   那些舊場次會突然變成「沒有攜幼時段」，過去的報到顏色就會跟著改變。
--
-- 所以這兩行只是把「本來就在用的預設值」正式寫進資料庫，
-- 現有場次的行為完全不變。報到紀錄、名單都不會被動到。
-- =========================================================

update sessions set xuanyu_deadline = '12:50' where xuanyu_deadline is null;
update sessions set other_open      = '13:15' where other_open      is null;

-- 之後建立新場次時，「攜幼／特殊開放入場」留空就代表這場沒有攜幼分流。
